#!/usr/bin/env bash
set -euo pipefail
repo_root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$repo_root"

expected=(
  apriltag_ffi.c
  client.js
  gpio_read.js
  index.html
  index.js
  npu_smoke.js
  style.css
  tag_worker.js
  worker.js
)

bun install --frozen-lockfile
bun run typecheck
bun test
bun run build

mapfile -t actual < <(cd dist && find . -maxdepth 1 -type f -printf '%f\n' | LC_ALL=C sort)
mapfile -t wanted < <(printf '%s\n' "${expected[@]}" | LC_ALL=C sort)
if [ "${actual[*]}" != "${wanted[*]}" ]; then
  echo 'dist artifact layout changed' >&2
  echo 'expected:' >&2; printf '  %s\n' "${wanted[@]}" >&2
  echo 'actual:' >&2; printf '  %s\n' "${actual[@]}" >&2
  exit 1
fi

{
  printf '# KITTI turret deploy artifact manifest\n'
  printf '# generated by deploy/build.sh\n'
  (cd dist && sha256sum "${wanted[@]}")
} > dist/MANIFEST.sha256
